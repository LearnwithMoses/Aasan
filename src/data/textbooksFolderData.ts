export type MaterialType =
  | "textbook"
  | "guide"
  | "worksheet"
  | "model_paper"
  | "lab_manual"
  | "blueprint";

export type MediumType =
  | "tamil"
  | "english"
  | "hindi"
  | "malayalam"
  | "kannada"
  | "telugu";

export interface TextbookMaterial {
  id: string;
  title: string;
  nativeTitle?: string;
  type: MaterialType;
  format: "pdf" | "interactive" | "doc";
  fileSize?: string;
  pagesCount?: number;
  downloadUrl: string;
  previewUrl?: string;
  sourceAuthority: string;
  term?: "Term 1" | "Term 2" | "Term 3" | "Annual";
  description: string;
  chaptersIncluded?: string[];
  boardExamYear?: string;
}

export interface SubjectFolder {
  id: string;
  name: string;
  nativeName?: string;
  subjectCode?: string;
  category: "Language" | "Core Science" | "Mathematics" | "Social Sciences" | "Commerce & Vocational";
  color: string;
  iconName: "book" | "flask" | "calculator" | "globe" | "laptop" | "feather" | "briefcase";
  materials: TextbookMaterial[];
}

export interface ClassFolder {
  gradeLevel: number; // 1 to 12
  gradeLabel: string; // "Class 1", ..., "Class 12"
  stage: "primary" | "middle" | "secondary" | "higher_secondary";
  mediumsAvailable: MediumType[];
  subjects: SubjectFolder[];
}

export interface BoardFolder {
  id: string;
  name: string;
  nativeName?: string;
  shortName: string;
  stateOrRegion: string;
  officialPortalUrl: string;
  officialPortalName: string;
  description: string;
  badgeColor: string;
  mediums: { id: MediumType; label: string; nativeLabel?: string }[];
  classes: ClassFolder[];
}

