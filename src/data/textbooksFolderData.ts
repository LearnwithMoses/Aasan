// Helper search across all textbooks and materials
export function searchAllMaterials(query: string, boardId?: string, gradeLevel?: number, medium?: MediumType, materialType?: MaterialType) {
  const cleanQ = query.trim().toLowerCase();
  const results: {
    board: BoardFolder;
    classFolder: ClassFolder;
    subject: SubjectFolder;
    material: TextbookMaterial;
  }[] = [];

  const boardsToSearch = boardId
    ? ALL_BOARD_FOLDERS.filter((b) => b.id === boardId)
    : ALL_BOARD_FOLDERS;

  boardsToSearch.forEach((board) => {
    board.classes.forEach((cls) => {
      if (gradeLevel && cls.gradeLevel !== gradeLevel) return;
      if (medium && !cls.mediumsAvailable.includes(medium)) return;

      cls.subjects.forEach((subj) => {
        subj.materials.forEach((mat) => {
          if (materialType && mat.type !== materialType) return;

          const matchText =
            !cleanQ ||
            mat.title.toLowerCase().includes(cleanQ) ||
            (mat.nativeTitle && mat.nativeTitle.toLowerCase().includes(cleanQ)) ||
            mat.description.toLowerCase().includes(cleanQ) ||
            subj.name.toLowerCase().includes(cleanQ) ||
            (subj.nativeName && subj.nativeName.toLowerCase().includes(cleanQ)) ||
            board.name.toLowerCase().includes(cleanQ) ||
            cls.gradeLabel.toLowerCase().includes(cleanQ) ||
            (mat.chaptersIncluded &&
              mat.chaptersIncluded.some((c) => c.toLowerCase().includes(cleanQ)));

          if (matchText) {
            results.push({
              board,
              classFolder: cls,
              subject: subj,
              material: mat,
            });
          }
        });
      });
    });
  });

  return results;
}
